// Run with: node --experimental-strip-types scripts/performance/build-mini-thumbnails.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import sharp from 'sharp';
import {portfolioPhotos} from '../../app/photo-library.ts';

const root = path.resolve(import.meta.dirname, '../..');
const output = path.join(root, 'public/images/mini-thumbnails');
await fs.mkdir(output, {recursive:true});
const manifest = {};
const records = [];
for (const photo of portfolioPhotos.filter(photo => photo.height > photo.width * 1.2)) {
  const input = await fs.readFile(path.join(root, 'public', photo.src));
  const metadata = await sharp(input).metadata();
  const cropHeight = Math.round(metadata.width / 1.92);
  // Match the existing CSS framing: object-position: center 30%.
  const top = Math.round((metadata.height - cropHeight) * 0.3);
  const width = Math.min(768, metadata.width);
  const height = Math.round(width / 1.92);
  const version = createHash('sha256').update(input).update('mini-1.92-y30-q85-v1').digest('hex').slice(0,12);
  const filename = `${path.basename(photo.src, '.webp')}-${version}.webp`;
  const buffer = await sharp(input).extract({left:0, top, width:metadata.width, height:cropHeight})
    .resize(width,height).webp({quality:85,effort:6}).toBuffer();
  await fs.writeFile(path.join(output,filename),buffer);
  manifest[photo.src] = {src:`/images/mini-thumbnails/${filename}`,width,height};
  records.push({source:photo.src,thumbnail:manifest[photo.src],sourceBytes:input.length,thumbnailBytes:buffer.length});
}
await fs.writeFile(path.join(root,'app/mini-gallery-thumbnails.ts'),
  '// Generated by scripts/performance/build-mini-thumbnails.mjs; popup uses the original image.\n'+
  'export const miniGalleryThumbnails: Record<string, {src: string; width: number; height: number}> = '+
  JSON.stringify(manifest,null,2)+';\n');
await fs.writeFile(path.join(root,'development-docs/reports/086-mini-thumbnails.json'),JSON.stringify(records,null,2)+'\n');
console.log(`Generated ${records.length} portrait thumbnails; originals unchanged.`);
